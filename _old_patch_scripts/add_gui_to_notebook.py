"""
Script to add the interactive ipywidgets GUI to Section 15 of main.ipynb
"""

import json
from pathlib import Path

nb_path = Path('main.ipynb')
nb = json.load(open(nb_path, 'r', encoding='utf-8'))

gui_code = [
    "# 15. Interactive In-Notebook Exploration GUI with ipywidgets\n",
    "import ipywidgets as widgets\n",
    "from IPython.display import display, clear_output, HTML\n",
    "import matplotlib.pyplot as plt\n",
    "import numpy as np\n",
    "import pandas as pd\n",
    "from pathlib import Path\n",
    "\n",
    "from src.problem import create_ising_chain\n",
    "from src.processors import load_processor\n",
    "from src.routing import transpile_circuit, analyze_routing_overhead\n",
    "from src.metrics import find_optimal_trotter_step, predict_analytical_optimal_n\n",
    "from src.visualization import plot_trotter_error_tradeoff\n",
    "from qiskit_aer import AerSimulator\n",
    "from qiskit_aer.noise import NoiseModel, depolarizing_error, ReadoutError\n",
    "\n",
    "proc_A = load_processor(Path('processors/processor_A.json'))\n",
    "proc_B = load_processor(Path('processors/processor_B.json'))\n",
    "\n",
    "# Preset regimes for judges\n",
    "PRESETS = {\n",
    "    'Default TFIM Benchmark (N=4, J=1.0, h=0.5, T=1.0)': {\n",
    "        'N': 4, 'J': 1.0, 'h': 0.5, 'T': 1.0, 'order': 1, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    'Periodic Boundary Ring (PBC - Closed Ring, 0 SWAP vs 6 SWAPs)': {\n",
    "        'N': 4, 'J': 1.0, 'h': 0.5, 'T': 1.0, 'order': 1, 'pbc': True, 'err': 1.0\n",
    "    },\n",
    "    'Quantum Critical Point (h = J = 1.0)': {\n",
    "        'N': 4, 'J': 1.0, 'h': 1.0, 'T': 1.0, 'order': 1, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    'Strong-Field Regime (h = 1.5, J = 0.5)': {\n",
    "        'N': 4, 'J': 0.5, 'h': 1.5, 'T': 1.0, 'order': 1, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    '2nd-Order Strang Splitting (Quadratic Convergence)': {\n",
    "        'N': 4, 'J': 1.0, 'h': 0.5, 'T': 1.0, 'order': 2, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    'Long-Time Evolution Challenge (T = 2.0s)': {\n",
    "        'N': 4, 'J': 1.0, 'h': 0.5, 'T': 2.0, 'order': 1, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    'Fast 3-Qubit Chain (N = 3)': {\n",
    "        'N': 3, 'J': 1.0, 'h': 0.8, 'T': 1.2, 'order': 1, 'pbc': False, 'err': 1.0\n",
    "    },\n",
    "    'Custom Parameters': None\n",
    "}\n",
    "\n",
    "# Create GUI Controls\n",
    "preset_dropdown = widgets.Dropdown(\n",
    "    options=list(PRESETS.keys()),\n",
    "    value='Default TFIM Benchmark (N=4, J=1.0, h=0.5, T=1.0)',\n",
    "    description='Preset:',\n",
    "    layout=widgets.Layout(width='580px')\n",
    ")\n",
    "\n",
    "w_qubits = widgets.IntSlider(value=4, min=3, max=5, step=1, description='Qubits (N):', layout=widgets.Layout(width='320px'))\n",
    "w_J = widgets.FloatSlider(value=1.0, min=0.1, max=2.5, step=0.1, description='Coupling J:', layout=widgets.Layout(width='320px'))\n",
    "w_h = widgets.FloatSlider(value=0.5, min=0.1, max=2.5, step=0.1, description='Field h:', layout=widgets.Layout(width='320px'))\n",
    "w_T = widgets.FloatSlider(value=1.0, min=0.2, max=3.0, step=0.1, description='Time T (s):', layout=widgets.Layout(width='320px'))\n",
    "w_order = widgets.Dropdown(options=[('1st Order Lie-Trotter', 1), ('2nd Order Strang', 2)], value=1, description='Order:', layout=widgets.Layout(width='320px'))\n",
    "w_pbc = widgets.Checkbox(value=False, description='Periodic Boundary (PBC)', indent=False, layout=widgets.Layout(width='250px'))\n",
    "w_err = widgets.FloatSlider(value=1.0, min=0.1, max=4.0, step=0.1, description='2Q Noise (%):', layout=widgets.Layout(width='320px'))\n",
    "\n",
    "run_btn = widgets.Button(\n",
    "    description='▶ Run Trotter Simulation & Plot Sweet Spot (n*)',\n",
    "    button_style='primary',\n",
    "    layout=widgets.Layout(width='440px', height='40px', font_weight='bold')\n",
    ")\n",
    "\n",
    "out_widget = widgets.Output()\n",
    "\n",
    "def on_preset_change(change):\n",
    "    p = PRESETS.get(change['new'])\n",
    "    if p is not None:\n",
    "        w_qubits.value = p['N']\n",
    "        w_J.value = p['J']\n",
    "        w_h.value = p['h']\n",
    "        w_T.value = p['T']\n",
    "        w_order.value = p['order']\n",
    "        w_pbc.value = p['pbc']\n",
    "        w_err.value = p['err']\n",
    "\n",
    "preset_dropdown.observe(on_preset_change, names='value')\n",
    "\n",
    "def build_noise_model(err_2q):\n",
    "    noise = NoiseModel()\n",
    "    noise.add_all_qubit_quantum_error(depolarizing_error(0.001, 1), ['x', 'sx', 'rz'])\n",
    "    noise.add_all_qubit_quantum_error(depolarizing_error(err_2q, 2), ['cx'])\n",
    "    noise.add_all_qubit_readout_error(ReadoutError([[0.98, 0.02], [0.02, 0.98]]))\n",
    "    return noise\n",
    "\n",
    "def run_interactive_simulation(b=None):\n",
    "    with out_widget:\n",
    "        clear_output(wait=True)\n",
    "        N = int(w_qubits.value)\n",
    "        J = float(w_J.value)\n",
    "        h = float(w_h.value)\n",
    "        T = float(w_T.value)\n",
    "        order = int(w_order.value)\n",
    "        pbc = bool(w_pbc.value)\n",
    "        err_2q = float(w_err.value) / 100.0\n",
    "        shots = 2048\n",
    "        steps_range = [1, 2, 3, 4, 5, 6, 8, 10]\n",
    "\n",
    "        sim = create_ising_chain(num_qubits=N, J=J, h=h, periodic=pbc)\n",
    "        exact_state = sim.exact_evolved_state(None, T)\n",
    "        exact_E = sim.exact_energy_expectation(exact_state)\n",
    "\n",
    "        aer_A = AerSimulator(noise_model=build_noise_model(err_2q))\n",
    "        aer_B = AerSimulator(noise_model=build_noise_model(err_2q))\n",
    "\n",
    "        records_A, records_B = [], []\n",
    "        trot_errors = []\n",
    "\n",
    "        for n in steps_range:\n",
    "            # Ideal\n",
    "            ideal_sv = sim.ideal_statevector(T, n, order=order)\n",
    "            trot_E = sim.exact_energy_expectation(ideal_sv)\n",
    "            t_err = abs(trot_E - exact_E) / max(1e-9, abs(exact_E))\n",
    "            trot_errors.append(t_err)\n",
    "\n",
    "            # Circuits\n",
    "            qc_b = sim.build_trotter_circuit(T, n, order=order, basis=None)\n",
    "            qc_z = sim.build_trotter_circuit(T, n, order=order, basis='Z')\n",
    "            qc_x = sim.build_trotter_circuit(T, n, order=order, basis='X')\n",
    "\n",
    "            # Transpile A & B\n",
    "            tA = transpile_circuit(qc_b, proc_A, optimization_level=1, seed_transpiler=42)\n",
    "            rA = analyze_routing_overhead(qc_b, tA)\n",
    "            tB = transpile_circuit(qc_b, proc_B, optimization_level=1, seed_transpiler=42)\n",
    "            rB = analyze_routing_overhead(qc_b, tB)\n",
    "\n",
    "            # Execute\n",
    "            counts_Az = aer_A.run(transpile_circuit(qc_z, proc_A, optimization_level=1, seed_transpiler=42), shots=shots, seed_simulator=42).result().get_counts()\n",
    "            counts_Ax = aer_A.run(transpile_circuit(qc_x, proc_A, optimization_level=1, seed_transpiler=42), shots=shots, seed_simulator=42).result().get_counts()\n",
    "            eA, _ = sim.compute_energy_from_counts(counts_Az, counts_Ax, shots)\n",
    "\n",
    "            counts_Bz = aer_B.run(transpile_circuit(qc_z, proc_B, optimization_level=1, seed_transpiler=42), shots=shots, seed_simulator=42).result().get_counts()\n",
    "            counts_Bx = aer_B.run(transpile_circuit(qc_x, proc_B, optimization_level=1, seed_transpiler=42), shots=shots, seed_simulator=42).result().get_counts()\n",
    "            eB, _ = sim.compute_energy_from_counts(counts_Bz, counts_Bx, shots)\n",
    "\n",
    "            tot_err_A = abs(eA - exact_E) / max(1e-9, abs(exact_E))\n",
    "            noise_err_A = abs(eA - trot_E) / max(1e-9, abs(exact_E))\n",
    "            tot_err_B = abs(eB - exact_E) / max(1e-9, abs(exact_E))\n",
    "            noise_err_B = abs(eB - trot_E) / max(1e-9, abs(exact_E))\n",
    "\n",
    "            records_A.append({\n",
    "                'trotter_steps': n, 'depth': tA.depth(), 'two_qubit_ops': rA['transpiled_2q_gates'],\n",
    "                'swap_count': rA['effective_swaps'], 'total_error': tot_err_A, 'noise_error': noise_err_A,\n",
    "                'trotter_error': t_err\n",
    "            })\n",
    "            records_B.append({\n",
    "                'trotter_steps': n, 'depth': tB.depth(), 'two_qubit_ops': rB['transpiled_2q_gates'],\n",
    "                'swap_count': rB['effective_swaps'], 'total_error': tot_err_B, 'noise_error': noise_err_B,\n",
    "                'trotter_error': t_err\n",
    "            })\n",
    "\n",
    "        opt_A = find_optimal_trotter_step(records_A)\n",
    "        opt_B = find_optimal_trotter_step(records_B)\n",
    "        ana_B = predict_analytical_optimal_n(J, h, T, N, err_2q, order=order, periodic=pbc, processor_type='processor_B')\n",
    "\n",
    "        # Print Summary Card\n",
    "        b_str = 'Periodic Ring (PBC)' if pbc else 'Open Chain (OBC)'\n",
    "        display(HTML(f'''\n",
    "        <div style=\"background: #1E293B; color: #F8FAFC; padding: 16px; border-radius: 10px; border-left: 5px solid #38BDF8; margin-bottom: 16px;\">\n",
    "            <h3 style=\"margin: 0 0 8px 0; color: #38BDF8;\">⚡ Simulation Results: N={N} Spins | J={J} | h={h} | T={T}s | Order={order} | Boundary={b_str}</h3>\n",
    "            <p style=\"margin: 4px 0;\"><strong>Exact Ground Truth Energy:</strong> <code>{exact_E:.6f}</code></p>\n",
    "            <div style=\"display: flex; gap: 24px; margin-top: 10px; flex-wrap: wrap;\">\n",
    "                <div><strong>Processor A (Linear):</strong> Optimal n* = <span style=\"color: #F87171; font-weight: bold;\">{opt_A['optimal_n']}</span> | Min Error = <b>{opt_A['min_total_error']*100:.2f}%</b> (Depth: {opt_A['optimal_depth']}, CX: {opt_A['optimal_2q_gates']})</div>\n",
    "                <div><strong>Processor B (Heavy-Hex):</strong> Optimal n* = <span style=\"color: #38BDF8; font-weight: bold;\">{opt_B['optimal_n']}</span> | Min Error = <b>{opt_B['min_total_error']*100:.2f}%</b> (Depth: {opt_B['optimal_depth']}, CX: {opt_B['optimal_2q_gates']})</div>\n",
    "                <div><strong>Analytical Prediction:</strong> n* ~ <span style=\"color: #C084FC; font-weight: bold;\">{ana_B['analytical_n_continuous']:.2f}</span> (rounded: {ana_B['analytical_n_optimal']})</div>\n",
    "            </div>\n",
    "        </div>\n",
    "        '''))\n",
    "\n",
    "        # DataFrame Table\n",
    "        df_res = pd.DataFrame({\n",
    "            'Steps (n)': steps_range,\n",
    "            'Trotter Error': [f\"{r['trotter_error']*100:.2f}%\" for r in records_A],\n",
    "            'Proc A Depth': [r['depth'] for r in records_A],\n",
    "            'Proc A CX (SWAPs)': [f\"{r['two_qubit_ops']} ({r['swap_count']})\" for r in records_A],\n",
    "            'Proc A Total Err': [f\"{r['total_error']*100:.2f}%\" for r in records_A],\n",
    "            'Proc B Depth': [r['depth'] for r in records_B],\n",
    "            'Proc B CX (SWAPs)': [f\"{r['two_qubit_ops']} ({r['swap_count']})\" for r in records_B],\n",
    "            'Proc B Total Err': [f\"{r['total_error']*100:.2f}%\" for r in records_B]\n",
    "        })\n",
    "        display(df_res)\n",
    "\n",
    "        # Plot U-Curve\n",
    "        fig, ax = plt.subplots(figsize=(10, 5), dpi=130)\n",
    "        ax.plot(steps_range, [r['trotter_error'] for r in records_A], '--', color='#90A4AE', linewidth=2, label='Algorithmic Trotter Error (Discretization)')\n",
    "        ax.plot(steps_range, [r['noise_error'] for r in records_B], ':', color='#FFA000', linewidth=2, label='Hardware Gate Noise Accumulation')\n",
    "        ax.plot(steps_range, [r['total_error'] for r in records_A], 'o-', color='#D32F2F', linewidth=2.4, label=f'Processor A Total Error (n* = {opt_A[\"optimal_n\"]})')\n",
    "        ax.plot(steps_range, [r['total_error'] for r in records_B], 's-', color='#1976D2', linewidth=2.6, label=f'Processor B Total Error (n* = {opt_B[\"optimal_n\"]})')\n",
    "        ax.axvline(x=opt_B['optimal_n'], color='#1976D2', linestyle=':', label=f'Sweet Spot n* = {opt_B[\"optimal_n\"]}')\n",
    "        ax.set_xlabel('Trotter Steps (n)', fontsize=11, fontweight='bold')\n",
    "        ax.set_ylabel('Total Relative Error', fontsize=11, fontweight='bold')\n",
    "        ax.set_title(f'Live Trotter Tradeoff U-Curve (N={N}, J={J}, h={h}, T={T}s, Order={order})', fontsize=12, fontweight='bold')\n",
    "        ax.legend(framealpha=0.9)\n",
    "        ax.grid(True, linestyle=':', alpha=0.6)\n",
    "        plt.tight_layout()\n",
    "        plt.show()\n",
    "\n",
    "run_btn.on_click(run_interactive_simulation)\n",
    "\n",
    "# Display UI Layout\n",
    "controls_grid = widgets.VBox([\n",
    "    preset_dropdown,\n",
    "    widgets.HBox([w_qubits, w_J]),\n",
    "    widgets.HBox([w_h, w_T]),\n",
    "    widgets.HBox([w_order, w_err]),\n",
    "    widgets.HBox([w_pbc, run_btn]),\n",
    "    widgets.HTML('''\n",
    "    <div style=\"margin: 10px 0; padding: 10px 14px; background: #0F172A; border-radius: 8px; border: 1px solid #334155; font-size: 13px;\">\n",
    "        💡 <b>Tip:</b> Choose any preset from the dropdown above, adjust the sliders, and click the blue Run button.<br>\n",
    "        🌐 Alternatively, open the standalone web dashboard: <a href=\"interactive_dashboard.html\" target=\"_blank\" style=\"color: #38BDF8; font-weight: bold;\">Open interactive_dashboard.html</a>\n",
    "    </div>\n",
    "    ''')\n",
    "])\n",
    "\n",
    "display(controls_grid)\n",
    "display(out_widget)\n",
    "\n",
    "# Run default benchmark once on load\n",
    "run_interactive_simulation()\n"
]

nb['cells'][27]['source'] = gui_code
nb['cells'][27]['outputs'] = []
nb['cells'][27]['execution_count'] = None

with open(nb_path, 'w', encoding='utf-8') as f:
    json.dump(nb, f, indent=1)

print('Successfully added interactive ipywidgets GUI to Section 15 of main.ipynb!')
